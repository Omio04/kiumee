# "뭘 할 수 있어?" 류: 이 화면에서 무엇을 고를 수 있는지 묻는 말
_SCREEN_Q = re.compile(
    r"(뭐|뭘|무엇|뭐를)\s*(가\s*)?(있|할\s*수|눌러|해야|고르|선택|하면)|어떻게\s*(해|하|주문|누르)|뭐부터|다음.*(뭐|어떻게)"
    r"|뭐\s*해야|뭘\s*해|어디.*눌러|무엇을\s*해"
)


def is_info_question(utterance: Optional[str]) -> bool:
    """메뉴 · 옵션을 설명해 달라는 질문인가 ("카페라떼가 뭐야?")."""
    return bool(utterance) and bool(_INFO.search(utterance.lower()))


def is_screen_question(utterance: Optional[str]) -> bool:
    """이 화면에서 뭘 할 수 있는지 묻는 말인가 ("뭘 눌러야 돼요?")."""
    return bool(utterance) and not is_info_question(utterance) and bool(_SCREEN_Q.search(utterance.lower()))


def _lookup(text: str) -> Optional[Tuple[str, str]]:
    """(보여 줄 이름, 설명). 이름이 영문이면 이름 없이 설명만 ("HOT은"을 어떻게 읽을지 정할 수 없다)."""
    n = normalize(text)
    if not n:
        return None
    for key, name, desc in _KEYS:
        if key in n:
            return (name if name.isascii() else name), desc
    return None


def _topic(name: str) -> str:
    """"카페라떼는" · "샷 추가는": 마지막 글자 받침에 따라 은/는."""
    last = name.strip()[-1:]
    if "가" <= last <= "힣":
        return name + ("은" if (ord(last) - 0xAC00) % 28 else "는")
    return name


def _named(hit: Tuple[str, str]) -> str:
    name, desc = hit
    return desc if name.isascii() else f"{_topic(name)} {desc}"


def explain(utterance: str, history: Sequence[HistoryItem]) -> Optional[str]:
    """질문에 나온 메뉴를 사전에서 찾아 설명 + 되물음 한 문장. 메뉴 이름이 없으면("이거 뭐야") 방금 안내한 버튼을 가리킨다고 본다.
    모르는 메뉴면 None (→ LLM)."""
    hit = _lookup(utterance)
    if hit is None:
        last = next((h for h in reversed(history) if h.action == ActionType.TAP and h.targetText), None)
        hit = _lookup(last.targetText) if last else None
    if hit is None:
        return None
    # 이름을 앞에 붙인다: 설명 뒤에 "그걸로 할게요"라고 하면 무엇인지 이력의 이 문장에서 알 수 있어야 한다
    text = _named(hit) + FOLLOW_UP
    if len(text) <= MAX_EXPLAIN:
        return text
    return (hit[1] + FOLLOW_UP)[:MAX_EXPLAIN]
